func TestEventsEndpoint(t *testing.T) {
	h := newHandler(t)
	_, created := call(t, h, "POST", "/v1/workloads", "acme", endpointBody)
	id := created["id"].(string)

	code, body := call(t, h, "GET", "/v1/workloads/"+id+"/events", "acme", "")
	items, _ := body["items"].([]any)
	if code != 200 || len(items) != 1 {
		t.Fatalf("events: %d %v", code, body)
	}
	first := items[0].(map[string]any)
	if first["to"] != "pending" || !strings.Contains(first["reason"].(string), "created by") {
		t.Errorf("first event = %v", first)
	}
	if code, _ := call(t, h, "GET", "/v1/workloads/"+id+"/events", "globex", ""); code != 404 {
		t.Errorf("cross-tenant events must be 404, got %d", code)
	}
}

func TestExportEndpoint(t *testing.T) {
	h := newHandler(t)
	_, created := call(t, h, "POST", "/v1/workloads", "acme", endpointBody)
	id := created["id"].(string)

	req := httptest.NewRequest("GET", "/v1/workloads/"+id+"/export", nil)
	req.Header.Set("X-Dev-Tenant", "acme")
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, req)
	if rec.Code != 200 {
		t.Fatalf("export: %d %s", rec.Code, rec.Body)
	}
	want := `attachment; filename=tensora-llm-` + id + `.json`
	if got := rec.Header().Get("Content-Disposition"); got != want {
		t.Errorf("Content-Disposition = %q, want %q", got, want)
	}
	var exp map[string]any
	if err := json.Unmarshal(rec.Body.Bytes(), &exp); err != nil {
		t.Fatal(err)
	}
	for _, key := range []string{"format", "exported_at", "exported_by", "workload", "created_by", "params", "events", "usage", "output_logs", "redactions"} {
		if _, ok := exp[key]; !ok {
			t.Errorf("export is missing %q", key)
		}
	}
	if exp["format"] != "tensora.workload-export/v1" || exp["params"].(map[string]any)["model_uri"] != "hf://Qwen/Qwen2.5-0.5B-Instruct" {
		t.Errorf("export = %v", exp)
	}
	if code, _ := call(t, h, "GET", "/v1/workloads/"+id+"/export", "globex", ""); code != 404 {
		t.Errorf("cross-tenant export must be 404, got %d", code)
	}
}

func TestRequestIDs(t *testing.T) {
	var logs bytes.Buffer
	st := testutil.SeededStore(t)
	h := api.New(service.New(st, testutil.Catalog(t), nil), auth.Dev{}, slog.New(slog.NewTextHandler(&logs, nil)), st.Ping).Handler()

	// Generated by the server, returned in the header and in error bodies.
	req := httptest.NewRequest("GET", "/v1/workloads", nil)
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, req)
	id := rec.Header().Get("X-Request-ID")
	var body struct {
		Error struct {
			RequestID string `json:"request_id"`
		} `json:"error"`
	}
	_ = json.Unmarshal(rec.Body.Bytes(), &body)
	if rec.Code != http.StatusUnauthorized || id == "" || body.Error.RequestID != id {
		t.Fatalf("status %d, header %q, body request_id %q", rec.Code, id, body.Error.RequestID)
	}

	// A caller's ID is never reused, so an ID always means exactly one request. A well-formed one is
	// logged as client_request_id; a hostile one is dropped.
	for in, logged := range map[string]bool{"trace-123_abc.9": true, "bad id\nInjected: header": false, strings.Repeat("x", 65): false} {
		logs.Reset()
		req := httptest.NewRequest("GET", "/v1/workloads", nil)
		req.Header.Set("X-Request-ID", in)
		req.Header.Set("X-Dev-Tenant", "acme")
		rec := httptest.NewRecorder()
		h.ServeHTTP(rec, req)
		got := rec.Header().Get("X-Request-ID")
		if got == in || got == "" {
			t.Errorf("X-Request-ID %q → %q; the server must generate its own", in, got)
		}
		line := logs.String()
		if strings.Contains(line, "client_request_id="+in) != logged {
			t.Errorf("client ID %q logged=%v:\n%s", in, !logged, line)
		}
		// Who made the request is on its log line, so an operator can check who owns a request ID.
		if !strings.Contains(line, "request_id="+got) || !strings.Contains(line, "tenant=acme") || !strings.Contains(line, "subject=") {
			t.Errorf("request log line lacks the ID or the caller:\n%s", line)
		}
	}
}

func TestDeletedWorkloadsAreReachable(t *testing.T) {
	st := testutil.SeededStore(t)
	svc := service.New(st, testutil.Catalog(t), nil)
	h := api.New(svc, auth.Dev{}, slog.New(slog.DiscardHandler), st.Ping).Handler()
	_, created := call(t, h, "POST", "/v1/workloads", "acme", endpointBody)
	id := created["id"].(string)
	ctx := context.Background()
	w, err := svc.GetWorkload(ctx, testutil.Acme, uuid.MustParse(id))
	if err != nil {
		t.Fatal(err)
	}
	err = st.InTx(ctx, func(q store.Queries) error {
		for _, to := range []domain.State{domain.StateDeleting, domain.StateDeleted} {
			if err := service.Transition(ctx, q, &w, to, "test", testutil.T0); err != nil {
				return err
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}

	if code, _ := call(t, h, "GET", "/v1/workloads/"+id, "acme", ""); code != 404 {
		t.Errorf("deleted workload by default: %d, want 404", code)
	}
	if code, body := call(t, h, "GET", "/v1/workloads/"+id+"?include_deleted=true", "acme", ""); code != 200 || body["state"] != "deleted" {
		t.Errorf("deleted workload with include_deleted: %d %v", code, body)
	}
	if code, _ := call(t, h, "GET", "/v1/workloads/"+id+"?include_deleted=true", "globex", ""); code != 404 {
		t.Errorf("another tenant's deleted workload: %d, want 404", code)
	}
	if _, body := call(t, h, "GET", "/v1/workloads", "acme", ""); len(body["items"].([]any)) != 0 {
		t.Errorf("default list includes deleted workloads: %v", body)
	}
	if _, body := call(t, h, "GET", "/v1/workloads?include_deleted=true", "acme", ""); len(body["items"].([]any)) != 1 {
		t.Errorf("list with include_deleted: %v", body)
	}
	if code, _ := call(t, h, "GET", "/v1/workloads?include_deleted=maybe", "acme", ""); code != 400 {
		t.Errorf("bad include_deleted: %d, want 400", code)
	}
}

// While a restarted workload waits, its previous run's placement isn't where it will run, so it
// isn't shown (the timeline keeps the history).
func TestWaitingWorkloadShowsNoStalePlacement(t *testing.T) {
	st := testutil.SeededStore(t)
	svc := service.New(st, testutil.Catalog(t), nil)
	h := api.New(svc, auth.Dev{}, slog.New(slog.DiscardHandler), st.Ping).Handler()
	_, created := call(t, h, "POST", "/v1/workloads", "acme", endpointBody)
	id := uuid.MustParse(created["id"].(string))
	ctx := context.Background()
	w, err := svc.GetWorkload(ctx, testutil.Acme, id)
	if err != nil {
		t.Fatal(err)
	}
	// Placed on acme's own machine, with a driver (ADR-0016).
	machine := uuid.New()
	transition := func(states ...domain.State) {
		t.Helper()
		if err := st.InTx(ctx, func(q store.Queries) error {
			for _, to := range states {
				if err := service.Transition(ctx, q, &w, to, "test", testutil.T0); err != nil {
					return err
				}
			}
			return nil
		}); err != nil {
			t.Fatal(err)
		}
	}
	err = st.InTx(ctx, func(q store.Queries) error {
		acme, err := q.TenantBySlug(ctx, "acme")
		if err != nil {
			return err
		}
		if err := q.CreateMachine(ctx, domain.Machine{ID: machine, TenantID: acme.ID, Name: "acme-box", Region: domain.RegionLocal,
			OS: "linux", Arch: "amd64", Sharing: domain.SharingPrivate, CreatedAt: testutil.T0}); err != nil {
			return err
		}
		if err := q.SetPlacement(ctx, id, "l40s-48gb", machine, domain.DriverDocker); err != nil {
			return err
		}
		w.PlacedClass, w.MachineID, w.Driver = "l40s-48gb", machine, domain.DriverDocker
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	transition(domain.StateProvisioning)
	if _, body := call(t, h, "GET", "/v1/workloads/"+id.String(), "acme", ""); body["machine_id"] != machine.String() || body["driver"] != "docker" {
		t.Errorf("placed workload view = %v; want its machine and driver", body)
	}
	transition(domain.StateFailed, domain.StatePending)
	if _, body := call(t, h, "GET", "/v1/workloads/"+id.String(), "acme", ""); body["state"] != "pending" ||
		body["placed_class"] != nil || body["machine_id"] != nil || body["driver"] != nil {
		t.Errorf("waiting workload view = %v; want no placement", body)
	}
	// The export keeps the stored placement, so it stays complete.
	if _, body := call(t, h, "GET", "/v1/workloads/"+id.String()+"/export", "acme", ""); body["last_placed_class"] != "l40s-48gb" ||
		body["last_machine_id"] != machine.String() || body["last_driver"] != "docker" {
		t.Errorf("export = %v; want the last placement", body)
	}
}
